function Cnormalised = normaliseConcentrationField(C)

    finiteValues = C(isfinite(C));

    if isempty(finiteValues)
        Cnormalised = C;
        return
    end

    cLo = min(finiteValues);
    cHi = max(finiteValues);

    if cHi-cLo <= 1.0e-12
        Cnormalised = ones(size(C));
    else
        Cnormalised = (C-cLo)/(cHi-cLo);
    end

    Cnormalised = max(0,min(1,Cnormalised));
end


