    imagesc(ax,xVector,yVector,speed);
    set(ax,'YDir','normal');

    hold(ax,'on')

    hStream = streamslice(ax,X,Y,U,V,density);

    if ~isempty(hStream)
        set(hStream, ...
            'Color','w', ...
            'LineWidth',0.65);
    end

    clim(ax,[0 velocityMax]);
    colormap(ax,parula(256));

    xlim(ax,xLimits);
    ylim(ax,yLimits);

    axis(ax,'image');

    xlabel(ax,'$x$ (m)','Interpreter','latex');
    ylabel(ax,'$z$ (m)','Interpreter','latex');

    cb = colorbar(ax);

    ylabel( ...
        cb, ...
        '$|\mathbf{u}|$ (m s$^{-1}$)', ...
        'Interpreter','latex');

    set(ax, ...
        'FontSize',13, ...
        'LineWidth',1.1, ...
        'Box','on');

    exportgraphics( ...
        fig, ...
        fullfile(outputFolder,filename), ...
        'Resolution',resolution, ...
        'BackgroundColor','white');

    close(fig)
end


function exportTimeHeightMap( ...
    times, ...
    zOverH, ...
    values, ...
    colourLimits, ...
    reverseGrey, ...
    colourbarLabel, ...
    outputFile)


    % TIME-HEIGHT DISPLAY
    %
    % IMPORTANT:
    % The quantitative values passed into this function are NOT
    % changed or re-saved.  For plotting only, the 4-mm vertical-bin
    % values are linearly interpolated onto a finer z/H grid.  This
    % avoids the artificial blocky striping produced by imagesc when
    % only 50 vertical bins are displayed at thesis resolution.


    times = times(:)';
    zOverH = zOverH(:);

    plotTimes = times;
    plotZ = zOverH;
    plotValues = values;

    % These values mirror the user settings at the top of the script.
    % Kept local so this function remains self-contained.
    useDisplayInterpolation = true;
    nZDisplay = 350;

    if ...
        useDisplayInterpolation ...
        && ...
        numel(times) >= 2 ...
        && ...
        numel(zOverH) >= 2

        plotZ = linspace( ...
            zOverH(1), ...
            zOverH(end), ...
            nZDisplay)';

        % Keep the original saved time coordinates.  Only the vertical
        % display direction is refined, so no additional temporal
        % behaviour is invented between saved FEniCS fields.
        plotTimes = times;

        plotValues = interp1( ...
            zOverH, ...
            values, ...
            plotZ, ...
            'linear');
    end

    fig = figure( ...
        'Color','w', ...
        'Visible','off', ...
        'Units','pixels', ...
        'Position',[100 100 1200 800]);

    ax = axes('Parent',fig);

    imagesc( ...
        ax, ...
        plotTimes, ...
        plotZ, ...
        plotValues);

    set(ax,'YDir','normal');

    xlim(ax,[times(1) times(end)]);
    ylim(ax,[0 1]);

    if ~isempty(colourLimits)
        clim(ax,colourLimits);
    end

    if reverseGrey
        colormap(ax,flipud(gray(256)));
    else
        colormap(ax,gray(256));
    end

    xlabel(ax,'$t$ (s)','Interpreter','latex');
    ylabel(ax,'$z/H$','Interpreter','latex');

    cb = colorbar(ax);

    ylabel( ...
        cb, ...
        colourbarLabel, ...
        'Interpreter','latex');

    set(ax, ...
        'FontSize',14, ...
        'LineWidth',1.2, ...
        'Box','on');

    exportgraphics( ...
        fig, ...
        outputFile, ...
        'Resolution',300, ...
        'BackgroundColor','white');

    close(fig)
end

