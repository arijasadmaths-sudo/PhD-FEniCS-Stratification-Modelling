function [coords,values] = readVectorDatasetWithGeometry(h5File,datasetPath)

    coords = readGeometry(h5File);
    raw = double(h5read(h5File,datasetPath));

    nPoints = size(coords,1);

    if ismatrix(raw) && size(raw,1) == nPoints && size(raw,2) == 3

        values = raw;

    elseif ismatrix(raw) && size(raw,2) == nPoints && size(raw,1) == 3

        values = raw';

    elseif numel(raw) == 3*nPoints

        % HDF5 vector data is commonly returned as 3 x N by MATLAB.
        values = reshape(raw,3,nPoints)';

    else

        error([ ...
            'Velocity dataset %s in %s has %d values, ' ...
            'but its XDMF geometry has %d points.'], ...
            datasetPath, ...
            h5File, ...
            numel(raw), ...
            nPoints)
    end
end


function index = nearestSeriesIndex(series,targetTime,tolerance)

    if isempty(series)
        index = 0;
        return
    end

    seriesTimes = [series.time];
    [difference,indexCandidate] = min(abs(seriesTimes-targetTime));

    if difference <= tolerance
        index = indexCandidate;
    else
        index = 0;
    end
end


