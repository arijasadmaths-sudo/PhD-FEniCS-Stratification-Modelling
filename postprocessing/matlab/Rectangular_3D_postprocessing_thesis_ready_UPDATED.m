function series = discoverXDMFSeries(rootFolder,baseName)

    files = dir(fullfile(rootFolder,'**',[baseName '.xdmf']));

    % Some MATLAB versions do not include the root itself in ** searches.
    directFile = fullfile(rootFolder,[baseName '.xdmf']);

    if isfile(directFile)

        alreadyIncluded = false;

        for j = 1:numel(files)
            thisPath = fullfile(files(j).folder,files(j).name);

            if strcmp(thisPath,directFile)
                alreadyIncluded = true;
                break
            end
        end

        if ~alreadyIncluded
            extra = dir(directFile);
            files = [files; extra];
        end
    end

    series = struct( ...
        'time',{}, ...
        'xdmfFile',{}, ...
        'h5File',{}, ...
        'datasetPath',{});

    for iFile = 1:numel(files)

        xdmfPath = fullfile(files(iFile).folder,files(iFile).name);

        [folderPath,fileStem,~] = fileparts(xdmfPath);

        h5Path = fullfile(folderPath,[fileStem '.h5']);

        if ~isfile(h5Path)
            warning('Skipping %s because matching H5 file is absent.',xdmfPath)
            continue
        end

        xmlText = fileread(xdmfPath);

        timeTokens = regexp( ...
            xmlText, ...
            '<Time\s+Value="([^"]+)"', ...
            'tokens');

        if isempty(timeTokens)
            warning('No saved times found in %s. Skipping.',xdmfPath)
            continue
        end

        localTimes = zeros(numel(timeTokens),1);

        for k = 1:numel(timeTokens)
            localTimes(k) = str2double(timeTokens{k}{1});
        end

        datasetTokens = regexp( ...
            xmlText, ...
            '\.h5:(/VisualisationVector/[0-9]+)', ...
            'tokens');

        localPaths = cell(numel(localTimes),1);

        if numel(datasetTokens) >= numel(localTimes)

            allPaths = cell(numel(datasetTokens),1);

            for k = 1:numel(datasetTokens)
                allPaths{k} = datasetTokens{k}{1};
            end

            uniquePaths = unique(allPaths,'stable');

            if numel(uniquePaths) >= numel(localTimes)
                localPaths = uniquePaths(1:numel(localTimes));
            else
                for k = 1:numel(localTimes)
                    localPaths{k} = sprintf( ...
                        '/VisualisationVector/%d', ...
                        k-1);
                end
            end
        else
            for k = 1:numel(localTimes)
                localPaths{k} = sprintf( ...
                    '/VisualisationVector/%d', ...
                    k-1);
            end
        end

        for k = 1:numel(localTimes)

            entry.time = localTimes(k);
            entry.xdmfFile = xdmfPath;
            entry.h5File = h5Path;
            entry.datasetPath = localPaths{k};

            series(end+1) = entry; %#ok<AGROW>
        end
    end

    if isempty(series)
        return
    end

    [~,order] = sort([series.time]);
    series = series(order);

    % Restart segment boundaries contain the same physical time twice.
    % Keep the later file and remove duplicate times to 1e-9 s.
    keep = true(1,numel(series));

    for k = 2:numel(series)

        if abs(series(k).time-series(k-1).time) <= 1.0e-9
            keep(k-1) = false;
        end
    end

    series = series(keep);
end


function requestedTimes = makeRequestedTimes(finalTime,spacing)

    if finalTime <= 0
        requestedTimes = finalTime;
        return
    end

    requestedTimes = spacing:spacing:finalTime;

    if isempty(requestedTimes)
        requestedTimes = finalTime;
    elseif abs(requestedTimes(end)-finalTime) > 1.0e-9
        requestedTimes = [requestedTimes finalTime];
    end
end


function [indices,selectedTimes] = nearestSavedTimes(times,requestedTimes)

    indices = zeros(numel(requestedTimes),1);
    selectedTimes = zeros(numel(requestedTimes),1);

    for j = 1:numel(requestedTimes)
        [~,indices(j)] = min(abs(times-requestedTimes(j)));
        selectedTimes(j) = times(indices(j));
    end

    [indices,uniquePosition] = unique(indices,'stable');
    selectedTimes = selectedTimes(uniquePosition);
end


