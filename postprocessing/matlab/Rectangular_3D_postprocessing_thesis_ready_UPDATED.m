%% ================================================================
%  3D RECTANGULAR FEniCS POST-PROCESSING -- THESIS-READY
%
%  Designed for the restartable 3D rectangular H(div) calculation.
%
%  Main outputs:
%    * stitched concentration output across ALL restart segments
%    * full-range concentration slices, 0 <= c <= 1
%    * high-contrast concentration slices, user-set fixed contrast <= c <= 1
%    * per-time normalised concentration slices, 0 <= c_N <= 1
%    * x-z and y-z velocity streamlines at selected times
%    * full-tank and central-region horizontal averages
%    * normalised vertical fresh-water profiles
%    * absolute / contrast / normalised time-height maps
%    * final-time x-y plan slices
%    * fresh-water volume versus time
%    * MAT and CSV exports
%
%  IMPORTANT:
%  Run this script from either:
%
%    (a) the overall result root containing:
%          segments/segment_.../c_hdiv_v2.xdmf
%
%        -> ALL restart segments are found, sorted and de-duplicated
%
%    OR
%
%    (b) a single segment folder containing c_hdiv_v2.xdmf
%
%        -> only that segment is processed.
%
%  The file called u_hdiv_v2.xdmf in the production simulation stores
%  the accepted Taylor-Hood velocity used for visualisation.  The H(div)
%  reconstruction remains the conservative scalar-advection flux.



%% ================================================================
%  USER SETTINGS


dataRoot = pwd;

% Physical tank dimensions.
L = 0.600;
W = 0.300;
H = 0.200;

xMinExpected = -L/2;
xMaxExpected =  L/2;
yMinExpected = -W/2;
yMaxExpected =  W/2;
zMinExpected = 0.0;
zMaxExpected = H;


% Thesis concentration settings


% The production concentration is already physically normalised:
%   c = 0 : fresh water
%   c = 1 : saline ambient
%
% Full-range images therefore use [0,1].
%
% The contrast images deliberately show only the upper concentration
% range.  This is the version that reveals the weak ceiling layer.
contrastLower = 0.85;

% Concentration snapshots every 0.5 s.
sliceTimeSpacing = 0.5;

% Mean-profile curves every 3 s.
% For an 18 s run this naturally gives:
%   3, 6, 9, 12, 15, 18 s
profileTimeSpacing = 3.0;

% Velocity streamlines every 2 s.
streamlineTimeSpacing = 2.0;


% Horizontal averaging


% 50 bins -> dz = 4 mm.
% This is deliberately coarser than the smallest local mesh spacing.
nZBins = 50;

% Central plume-focused region: 6 cm x 6 cm.
centralHalfWidthX = 0.030;
centralHalfWidthY = 0.030;


% Visual slices


% Concentration is cell-centred DG0.  Thin slabs are therefore used
% only for visual interpolation, not for quantitative averaging.
sliceHalfThicknessXZ = 0.008;     % |y| <= 8 mm
sliceHalfThicknessYZ = 0.008;     % |x| <= 8 mm
sliceHalfThicknessXY = 0.006;     % final x-y plan views

% Velocity visualisation is nodal.  Use a slightly thinner central slab.
velocitySliceHalfThickness = 0.006;

% Plot grids.
nxXZ = 900;
nzXZ = 300;

nyYZ = 600;
nzYZ = 400;

nxXY = 900;
nyXY = 450;

% Final-time horizontal plan views.
planZFractions = [0.25 0.50 0.75 0.95];

% Streamline density.
streamlineDensity = 1.15;

% Fixed velocity-magnitude display range for comparison between times.
% The discrete inlet peak is ~0.2132 m/s.
velocityDisplayMax = 0.22;

% Output resolution.
pngResolution = 400;
thesisPngResolution = 600;


% Time-height display interpolation

%
% Horizontal averages are STILL calculated from the original
% volume-weighted DG0 data and saved unchanged to MAT/CSV.
%
% This setting affects ONLY the plotted time-height images.  The
% binned values are linearly interpolated onto a finer display grid
% so the thesis figures do not appear as blocky horizontal strips.
smoothTimeHeightForDisplay = true;
nZTimeHeightDisplay = 350;


%% ================================================================
%  OUTPUT FOLDERS


contrastTag = strrep(sprintf('%.2f',contrastLower),'.','p');

resultsFolder = fullfile( ...
    dataRoot, ...
    'MATLAB_3D_rectangular_postprocessing_thesis_ready');

if ~exist(resultsFolder,'dir')
    mkdir(resultsFolder)
end

% Concentration folders.
xzFullFolder = fullfile(resultsFolder,'01_concentration_xz_full_0_to_1');
yzFullFolder = fullfile(resultsFolder,'02_concentration_yz_full_0_to_1');

xzContrastFolder = fullfile( ...
    resultsFolder, ...
    ['03_concentration_xz_contrast_' contrastTag '_to_1_thesis']);

yzContrastFolder = fullfile( ...
    resultsFolder, ...
    ['04_concentration_yz_contrast_' contrastTag '_to_1_thesis']);

xzNormalisedFolder = fullfile( ...
    resultsFolder, ...
    '05_concentration_xz_per_time_normalised_0_to_1_thesis');

yzNormalisedFolder = fullfile( ...
    resultsFolder, ...
    '06_concentration_yz_per_time_normalised_0_to_1_thesis');

% Velocity folders.
xzStreamFolder = fullfile( ...
    resultsFolder, ...
    '07_velocity_xz_streamlines_clean_thesis');

yzStreamFolder = fullfile( ...
    resultsFolder, ...
    '08_velocity_yz_streamlines_clean_thesis');

xzVelocityFolder = fullfile( ...
    resultsFolder, ...
    '09_velocity_xz_magnitude_streamlines');

yzVelocityFolder = fullfile( ...
    resultsFolder, ...
    '10_velocity_yz_magnitude_streamlines');

% Plan-view folders.
xyFullFolder = fullfile( ...
    resultsFolder, ...
    '11_final_xy_plan_full_0_to_1');

xyContrastFolder = fullfile( ...
    resultsFolder, ...
    ['12_final_xy_plan_contrast_' contrastTag '_to_1_thesis']);

xyNormalisedFolder = fullfile( ...
    resultsFolder, ...
    '13_final_xy_plan_per_time_normalised_thesis');

foldersToCreate = { ...
    xzFullFolder, ...
    yzFullFolder, ...
    xzContrastFolder, ...
    yzContrastFolder, ...
    xzNormalisedFolder, ...
    yzNormalisedFolder, ...
    xzStreamFolder, ...
    yzStreamFolder, ...
    xzVelocityFolder, ...
    yzVelocityFolder, ...
    xyFullFolder, ...
    xyContrastFolder, ...
    xyNormalisedFolder};

for j = 1:numel(foldersToCreate)
    if ~exist(foldersToCreate{j},'dir')
        mkdir(foldersToCreate{j})
    end
end


%% ================================================================
%  DISCOVER + STITCH ALL RESTART SEGMENTS


fprintf('\n')
fprintf('================================================\n')
fprintf('DISCOVERING RECTANGULAR 3D FEniCS OUTPUT\n')
fprintf('================================================\n\n')

cSeries = discoverXDMFSeries( ...
    dataRoot, ...
    'c_hdiv_v2');

if isempty(cSeries)
    error([ ...
        'No c_hdiv_v2.xdmf files were found under:\n%s\n\n' ...
        'Run this script from the overall result root or a segment folder.'], ...
        dataRoot)
end

uSeries = discoverXDMFSeries( ...
    dataRoot, ...
    'u_hdiv_v2');

times = [cSeries.time]';
nTimes = numel(times);

velocityAvailable = ~isempty(uSeries);

fprintf('Concentration fields after stitching : %d\n',nTimes)
fprintf('First concentration time             : %.6f s\n',times(1))
fprintf('Last concentration time              : %.6f s\n',times(end))
fprintf('Velocity series available            : %d\n',velocityAvailable)
fprintf('Contrast display                     : %.3f to 1.000\n\n', ...
    contrastLower)

if velocityAvailable
    fprintf('Velocity fields after stitching      : %d\n',numel(uSeries))
    fprintf('Velocity time range                  : %.6f to %.6f s\n\n', ...
        uSeries(1).time, ...
        uSeries(end).time)
end


%% ================================================================
%  BUILD REQUESTED TIMES


sliceRequestedTimes = makeRequestedTimes( ...
    times(end), ...
    sliceTimeSpacing);

profileRequestedTimes = makeRequestedTimes( ...
    times(end), ...
    profileTimeSpacing);

streamlineRequestedTimes = makeRequestedTimes( ...
    times(end), ...
    streamlineTimeSpacing);

[sliceIndices,sliceTimes] = nearestSavedTimes( ...
    times, ...
    sliceRequestedTimes);

[profileIndices,profileTimes] = nearestSavedTimes( ...
    times, ...
    profileRequestedTimes);

[streamlineIndices,streamlineTimes] = nearestSavedTimes( ...
    times, ...
    streamlineRequestedTimes);

fprintf('Thesis concentration slice times:\n')
fprintf('  %.3f',sliceTimes)
fprintf('\n\n')

fprintf('Thesis profile times:\n')
fprintf('  %.3f',profileTimes)
fprintf('\n\n')

if velocityAvailable
    fprintf('Velocity streamline times:\n')
    fprintf('  %.3f',streamlineTimes)
    fprintf('\n\n')
end


%% ================================================================
%  READ REFERENCE CONCENTRATION MESH


referenceH5 = cSeries(1).h5File;

geometry = readGeometry(referenceH5);

topology = h5read( ...
    referenceH5, ...
    '/Mesh/0/mesh/topology');

if size(topology,2) ~= 4 && size(topology,1) == 4
    topology = topology';
end

if size(topology,2) ~= 4
    error('Unexpected tetrahedral topology dimensions in concentration H5.')
end

% FEniCS topology is zero-based.
tetra = double(topology) + 1;

nVertices = size(geometry,1);
nCells = size(tetra,1);

xMeshMin = min(geometry(:,1));
xMeshMax = max(geometry(:,1));
yMeshMin = min(geometry(:,2));
yMeshMax = max(geometry(:,2));
zMeshMin = min(geometry(:,3));
zMeshMax = max(geometry(:,3));

fprintf('Reference mesh:\n')
fprintf('  vertices = %d\n',nVertices)
fprintf('  cells    = %d\n',nCells)
fprintf('  x range  = %.6f to %.6f m\n',xMeshMin,xMeshMax)
fprintf('  y range  = %.6f to %.6f m\n',yMeshMin,yMeshMax)
fprintf('  z range  = %.6f to %.6f m\n\n',zMeshMin,zMeshMax)


%% ================================================================
%  GEOMETRY SANITY CHECK


geometryTolerance = 1.0e-8;

geometryIsCorrect = ...
    abs(xMeshMin-xMinExpected) < geometryTolerance ...
    && ...
    abs(xMeshMax-xMaxExpected) < geometryTolerance ...
    && ...
    abs(yMeshMin-yMinExpected) < geometryTolerance ...
    && ...
    abs(yMeshMax-yMaxExpected) < geometryTolerance ...
    && ...
    abs(zMeshMin-zMinExpected) < geometryTolerance ...
    && ...
    abs(zMeshMax-zMaxExpected) < geometryTolerance;

if ~geometryIsCorrect
    fprintf('\n')
    fprintf('================================================\n')
    fprintf('WRONG 3D GEOMETRY DETECTED\n')
    fprintf('================================================\n\n')
    fprintf('Expected:\n')
    fprintf('  x = -0.300 to +0.300 m\n')
    fprintf('  y = -0.150 to +0.150 m\n')
    fprintf('  z =  0.000 to +0.200 m\n\n')
    fprintf('Loaded:\n')
    fprintf('  x = %.6f to %.6f m\n',xMeshMin,xMeshMax)
    fprintf('  y = %.6f to %.6f m\n',yMeshMin,yMeshMax)
    fprintf('  z = %.6f to %.6f m\n',zMeshMin,zMeshMax)

    error('This is not the corrected rectangular experimental geometry.')
end

fprintf('RECTANGULAR GEOMETRY CHECK PASSED.\n\n')


%% ================================================================
%  TETRAHEDRON CENTRES + VOLUMES


P1 = geometry(tetra(:,1),:);
P2 = geometry(tetra(:,2),:);
P3 = geometry(tetra(:,3),:);
P4 = geometry(tetra(:,4),:);

cellCentre = (P1 + P2 + P3 + P4) / 4;

v21 = P2-P1;
v31 = P3-P1;
v41 = P4-P1;

cellVolume = abs( ...
    dot(v21,cross(v31,v41,2),2)) ...
    / 6;

xCell = cellCentre(:,1);
yCell = cellCentre(:,2);
zCell = cellCentre(:,3);

meshVolume = sum(cellVolume);
exactVolume = L*W*H;

fprintf('Tank-volume check:\n')
fprintf('  mesh volume  = %.12e m^3\n',meshVolume)
fprintf('  exact volume = %.12e m^3\n',exactVolume)
fprintf('  error        = %.6e %%\n\n', ...
    100*abs(meshVolume-exactVolume)/exactVolume)


%% ================================================================
%  VERTICAL BINS FOR HORIZONTAL AVERAGING


zEdges = linspace(0,H,nZBins+1);

zAverage = 0.5*( ...
    zEdges(1:end-1) ...
    + ...
    zEdges(2:end));

zAverage = zAverage(:);

cellLayer = discretize(zCell,zEdges);

validCells = ...
    ~isnan(cellLayer) ...
    & ...
    cellLayer >= 1 ...
    & ...
    cellLayer <= nZBins;

layerVolume = accumarray( ...
    cellLayer(validCells), ...
    cellVolume(validCells), ...
    [nZBins 1], ...
    @sum, ...
    0);

centralMask = ...
    abs(xCell) <= centralHalfWidthX ...
    & ...
    abs(yCell) <= centralHalfWidthY;

validCentral = validCells & centralMask;

centralLayerVolume = accumarray( ...
    cellLayer(validCentral), ...
    cellVolume(validCentral), ...
    [nZBins 1], ...
    @sum, ...
    0);

if any(layerVolume == 0)
    error([ ...
        'At least one full-tank z-bin has no cell centres. ' ...
        'Reduce nZBins.'])
end

if any(centralLayerVolume == 0)
    warning([ ...
        'Some central-region z-bins contain no cells. ' ...
        'Central mean will contain NaNs there.'])
end


%% ================================================================
%  VISUAL GRIDS


xXZ = linspace(-L/2,L/2,nxXZ);
zXZ = linspace(0,H,nzXZ);
[XXZ,ZXZ] = meshgrid(xXZ,zXZ);

yYZ = linspace(-W/2,W/2,nyYZ);
zYZ = linspace(0,H,nzYZ);
[YYZ,ZYZ] = meshgrid(yYZ,zYZ);

xXY = linspace(-L/2,L/2,nxXY);
yXY = linspace(-W/2,W/2,nyXY);
[XXY,YXY] = meshgrid(xXY,yXY);


%% ================================================================
%  STORAGE


cBarAll = nan(nZBins,nTimes);
cBarCentral = nan(nZBins,nTimes);

freshVolume = nan(nTimes,1);
cMinimum = nan(nTimes,1);
cMaximum = nan(nTimes,1);


%% ================================================================
%  PROCESS ALL CONCENTRATION FIELDS


fprintf('Processing stitched concentration series...\n\n')

for k = 1:nTimes

    cCell = readScalarDataset( ...
        cSeries(k).h5File, ...
        cSeries(k).datasetPath);

    if numel(cCell) ~= nCells
        error([ ...
            'Field at t = %.6f s has %d values, ' ...
            'but reference mesh has %d tetrahedra.'], ...
            times(k), ...
            numel(cCell), ...
            nCells)
    end

    cMinimum(k) = min(cCell);
    cMaximum(k) = max(cCell);


    % Full-tank volume-weighted horizontal mean.


    weightedFull = accumarray( ...
        cellLayer(validCells), ...
        cCell(validCells).*cellVolume(validCells), ...
        [nZBins 1], ...
        @sum, ...
        0);

    cBarAll(:,k) = ...
        weightedFull ...
        ./ ...
        layerVolume;


    % Central 6 cm x 6 cm volume-weighted mean.


    weightedCentral = accumarray( ...
        cellLayer(validCentral), ...
        cCell(validCentral).*cellVolume(validCentral), ...
        [nZBins 1], ...
        @sum, ...
        0);

    goodCentralBins = centralLayerVolume > 0;

    cBarCentral(goodCentralBins,k) = ...
        weightedCentral(goodCentralBins) ...
        ./ ...
        centralLayerVolume(goodCentralBins);


    % Total fresh-water volume.


    freshVolume(k) = sum( ...
        (1-cCell) ...
        .* ...
        cellVolume);


    % Thesis concentration slices.


    if any(sliceIndices == k)

        fprintf('  concentration slices at t = %.3f s\n',times(k))

        timeTag = timeToTag(times(k));


        % x-z concentration slice


        xzMask = abs(yCell) <= sliceHalfThicknessXZ;

        F_xz = scatteredInterpolant( ...
            xCell(xzMask), ...
            zCell(xzMask), ...
            cCell(xzMask), ...
            'linear', ...
            'nearest');

        Cxz = F_xz(XXZ,ZXZ);

        % Plotting only: remove tiny solver overshoots.
        Cxz = max(0,min(1,Cxz));

        exportScalarSlice( ...
            xXZ, ...
            zXZ, ...
            Cxz, ...
            [-L/2 L/2], ...
            [0 H], ...
            [0 1], ...
            [1800 600], ...
            xzFullFolder, ...
            ['xz_full_t_' timeTag 's.png'], ...
            pngResolution);

        exportScalarSlice( ...
            xXZ, ...
            zXZ, ...
            Cxz, ...
            [-L/2 L/2], ...
            [0 H], ...
            [contrastLower 1], ...
            [1800 600], ...
            xzContrastFolder, ...
            ['xz_contrast_' contrastTag '_t_' timeTag 's.png'], ...
            thesisPngResolution);

        CxzNormalised = normaliseConcentrationField(Cxz);

        exportScalarSlice( ...
            xXZ, ...
            zXZ, ...
            CxzNormalised, ...
            [-L/2 L/2], ...
            [0 H], ...
            [0 1], ...
            [1800 600], ...
            xzNormalisedFolder, ...
            ['xz_normalised_t_' timeTag 's.png'], ...
            thesisPngResolution);


        % y-z concentration slice


        yzMask = abs(xCell) <= sliceHalfThicknessYZ;

        F_yz = scatteredInterpolant( ...
            yCell(yzMask), ...
            zCell(yzMask), ...
            cCell(yzMask), ...
            'linear', ...
            'nearest');

        Cyz = F_yz(YYZ,ZYZ);
        Cyz = max(0,min(1,Cyz));

        exportScalarSlice( ...
            yYZ, ...
            zYZ, ...
            Cyz, ...
            [-W/2 W/2], ...
            [0 H], ...
            [0 1], ...
            [1200 800], ...
            yzFullFolder, ...
            ['yz_full_t_' timeTag 's.png'], ...
            pngResolution);

        exportScalarSlice( ...
            yYZ, ...
            zYZ, ...
            Cyz, ...
            [-W/2 W/2], ...
            [0 H], ...
            [contrastLower 1], ...
            [1200 800], ...
            yzContrastFolder, ...
            ['yz_contrast_' contrastTag '_t_' timeTag 's.png'], ...
            thesisPngResolution);

        CyzNormalised = normaliseConcentrationField(Cyz);

        exportScalarSlice( ...
            yYZ, ...
            zYZ, ...
            CyzNormalised, ...
            [-W/2 W/2], ...
            [0 H], ...
            [0 1], ...
            [1200 800], ...
            yzNormalisedFolder, ...
            ['yz_normalised_t_' timeTag 's.png'], ...
            thesisPngResolution);
    end

    if k == 1 || mod(k,10) == 0 || k == nTimes
        fprintf( ...
            '  processed %4d / %4d   t = %.3f s\n', ...
            k, ...
            nTimes, ...
            times(k))
    end
end

fprintf('\nAll concentration fields processed.\n\n')


%% ================================================================
%  VELOCITY STREAMLINES


if velocityAvailable

    fprintf('Processing velocity streamlines...\n\n')

    for j = 1:numel(streamlineTimes)

        tTarget = streamlineTimes(j);

        uIndex = nearestSeriesIndex( ...
            uSeries, ...
            tTarget, ...
            5.0e-8);

        if uIndex == 0
            warning( ...
                'No velocity field found at t = %.6f s. Skipping.', ...
                tTarget)
            continue
        end

        [uCoords,uValues] = readVectorDatasetWithGeometry( ...
            uSeries(uIndex).h5File, ...
            uSeries(uIndex).datasetPath);

        if size(uValues,2) < 3
            warning( ...
                'Velocity field at t = %.6f s is not 3-component. Skipping.', ...
                tTarget)
            continue
        end

        timeTag = timeToTag(tTarget);

        fprintf('  velocity streamlines at t = %.3f s\n',tTarget)


        % x-z streamlines, central slab around y = 0


        maskXZ = abs(uCoords(:,2)) <= velocitySliceHalfThickness;

        if nnz(maskXZ) >= 20

            Fux = scatteredInterpolant( ...
                uCoords(maskXZ,1), ...
                uCoords(maskXZ,3), ...
                uValues(maskXZ,1), ...
                'linear', ...
                'nearest');

            Fuz = scatteredInterpolant( ...
                uCoords(maskXZ,1), ...
                uCoords(maskXZ,3), ...
                uValues(maskXZ,3), ...
                'linear', ...
                'nearest');

            UxGrid = Fux(XXZ,ZXZ);
            UzGrid = Fuz(XXZ,ZXZ);

            speedXZ = sqrt(UxGrid.^2 + UzGrid.^2);

            exportCleanStreamlines( ...
                XXZ, ...
                ZXZ, ...
                UxGrid, ...
                UzGrid, ...
                [-L/2 L/2], ...
                [0 H], ...
                [1800 600], ...
                streamlineDensity, ...
                xzStreamFolder, ...
                ['xz_streamlines_t_' timeTag 's.png'], ...
                thesisPngResolution);

            exportVelocityMagnitudeStreamlines( ...
                xXZ, ...
                zXZ, ...
                XXZ, ...
                ZXZ, ...
                speedXZ, ...
                UxGrid, ...
                UzGrid, ...
                [-L/2 L/2], ...
                [0 H], ...
                [1800 600], ...
                streamlineDensity, ...
                velocityDisplayMax, ...
                xzVelocityFolder, ...
                ['xz_velocity_magnitude_streamlines_t_' timeTag 's.png'], ...
                pngResolution);
        else
            warning( ...
                'Too few velocity points for x-z streamlines at t = %.3f s.', ...
                tTarget)
        end


        % y-z streamlines, central slab around x = 0


        maskYZ = abs(uCoords(:,1)) <= velocitySliceHalfThickness;

        if nnz(maskYZ) >= 20

            Fuy = scatteredInterpolant( ...
                uCoords(maskYZ,2), ...
                uCoords(maskYZ,3), ...
                uValues(maskYZ,2), ...
                'linear', ...
                'nearest');

            FuzYZ = scatteredInterpolant( ...
                uCoords(maskYZ,2), ...
                uCoords(maskYZ,3), ...
                uValues(maskYZ,3), ...
                'linear', ...
                'nearest');

            UyGrid = Fuy(YYZ,ZYZ);
            UzGridYZ = FuzYZ(YYZ,ZYZ);

            speedYZ = sqrt(UyGrid.^2 + UzGridYZ.^2);

            exportCleanStreamlines( ...
                YYZ, ...
                ZYZ, ...
                UyGrid, ...
                UzGridYZ, ...
                [-W/2 W/2], ...
                [0 H], ...
                [1200 800], ...
                streamlineDensity, ...
                yzStreamFolder, ...
                ['yz_streamlines_t_' timeTag 's.png'], ...
                thesisPngResolution);

            exportVelocityMagnitudeStreamlines( ...
                yYZ, ...
                zYZ, ...
                YYZ, ...
                ZYZ, ...
                speedYZ, ...
                UyGrid, ...
                UzGridYZ, ...
                [-W/2 W/2], ...
                [0 H], ...
                [1200 800], ...
                streamlineDensity, ...
                velocityDisplayMax, ...
                yzVelocityFolder, ...
                ['yz_velocity_magnitude_streamlines_t_' timeTag 's.png'], ...
                pngResolution);
        else
            warning( ...
                'Too few velocity points for y-z streamlines at t = %.3f s.', ...
                tTarget)
        end
    end

    fprintf('\nVelocity streamline processing complete.\n\n')
else
    warning([ ...
        'No u_hdiv_v2.xdmf files were found. ' ...
        'Concentration processing will continue without velocity figures.'])
end


%% ================================================================
%  FINAL-TIME x-y PLAN SLICES


cFinal = readScalarDataset( ...
    cSeries(end).h5File, ...
    cSeries(end).datasetPath);

for j = 1:numel(planZFractions)

    zFraction = planZFractions(j);
    zTarget = zFraction*H;

    xyMask = ...
        abs(zCell-zTarget) ...
        <= ...
        sliceHalfThicknessXY;

    if nnz(xyMask) < 50
        warning( ...
            'Too few cells for x-y slice at z/H = %.2f.', ...
            zFraction)
        continue
    end

    F_xy = scatteredInterpolant( ...
        xCell(xyMask), ...
        yCell(xyMask), ...
        cFinal(xyMask), ...
        'linear', ...
        'nearest');

    Cxy = F_xy(XXY,YXY);
    Cxy = max(0,min(1,Cxy));

    zTag = strrep(sprintf('%0.2f',zFraction),'.','p');

    exportScalarSlice( ...
        xXY, ...
        yXY, ...
        Cxy, ...
        [-L/2 L/2], ...
        [-W/2 W/2], ...
        [0 1], ...
        [1600 800], ...
        xyFullFolder, ...
        ['xy_final_full_zOverH_' zTag '.png'], ...
        pngResolution);

    exportScalarSlice( ...
        xXY, ...
        yXY, ...
        Cxy, ...
        [-L/2 L/2], ...
        [-W/2 W/2], ...
        [contrastLower 1], ...
        [1600 800], ...
        xyContrastFolder, ...
        ['xy_final_contrast_' contrastTag '_zOverH_' zTag '.png'], ...
        thesisPngResolution);

    CxyNormalised = normaliseConcentrationField(Cxy);

    exportScalarSlice( ...
        xXY, ...
        yXY, ...
        CxyNormalised, ...
        [-L/2 L/2], ...
        [-W/2 W/2], ...
